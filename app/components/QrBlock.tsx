'use client'

import { QRCodeSVG } from 'qrcode.react'

/**
 * Квадрат QR для друкованої афіші.
 *
 * SVG, а не картинка: афішу друкують, і растр на папері мутніє. Рівень
 * корекції помилок M — компроміс між щільністю й тим, що аркуш на стіні
 * бібліотеки за місяць буде з відбитком пальця і загином кута.
 *
 * Клієнтський компонент лише тому, що бібліотека так позначена; жодного
 * стану тут немає, і при виключеному JavaScript код усе одно намалюється
 * після гідратації. Для друку це не важить: сторінку друкують із браузера.
 */
export default function QrBlock({ url, size = 220 }: { url: string; size?: number }) {
  return (
    <QRCodeSVG
      value={url}
      size={size}
      level="M"
      marginSize={2}
      bgColor="#ffffff"
      fgColor="#000000"
    />
  )
}
