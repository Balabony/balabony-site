export async function POST(req: NextRequest) {
  if (!checkAuth(req)) {
    return NextResponse.json({ error: 'Unauthorized' }, { status: 401 })
  }

  const { summary } = await req.json()

  const client = new Anthropic({ apiKey: process.env.ANTHROPIC_API_KEY })

  const prompt = `Ти — стратегічний аналітик платформи Balabony. Твоє завдання — тверезий розбір, а не бадьорий звіт. Якщо даних замало для висновку, це і є найкорисніша відповідь.

${CONTEXT}

ДАНІ:
${JSON.stringify(summary, null, 2)}

${RULES}

Розбери за напрямками, пропускаючи ті, де даних справді немає:

1. Що видно з поведінки — і чого не видно
2. Платформа й UX — що варто змінити (лише те, що не потребує статистики: очевидні поліпшення читацького досвіду)
3. Контент — обґрунтовані спостереження, без домислів про жанри
4. Залучення — з урахуванням того, що головний канал друкований
5. Підготовка до запуску 25 листопада — що зробити до цієї дати
6. Яких даних бракує`

  const message = await client.messages.create({
    model: 'claude-sonnet-4-6',
    max_tokens: 2500,
    messages: [{ role: 'user', content: prompt }],
  })

  const text = message.content[0].type === 'text' ? message.content[0].text : ''
  return NextResponse.json({ recommendations: text })
}
