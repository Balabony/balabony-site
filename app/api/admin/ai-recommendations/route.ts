import { NextRequest, NextResponse } from 'next/server'
import Anthropic from '@anthropic-ai/sdk'

/**
 * ШІ-аналіз даних платформи.
 *
 * Промпт містить канонічний контекст Balabony. Без нього модель домислює його
 * сама — і видає впевнені висновки на кшталт «авторів більше, ніж читачів»
 * (насправді це заходи команди в адмінку) або «попит на воєнну тематику»
 * (насправді це свіжо опубліковані серії «Тиші», які відкривала редакція).
 *
 * Другий запобіжник — правило малої вибірки: на десятках подій відсотки
 * нічого не означають, і модель має про це сказати, а не рахувати конверсії.
 *
 * Контекст правити тут, коли змінюються канонічні факти платформи.
 */

function checkAuth(req: NextRequest): boolean {
  const cookie = req.cookies.get('admin_session')?.value
  return cookie === process.env.ADMIN_PASSWORD
}

