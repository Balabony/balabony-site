interface GenerateBody {
  title?: string
  season?: string
  episode?: string
  character?: string
  genre?: string
  summary?: string
  styleContext?: string
}

// Легке прибирання markdown-символів по ходу стріму (зірочки/лапки),
// бо текст іде на озвучення й читання.
function stripInline(s: string): string {
  return s.replace(/[*`]/g, '')
}

export async function POST(request: NextRequest) {
  const apiKey = process.env.GEMINI_API_KEY
  if (!apiKey) {
    return new Response('GEMINI_API_KEY не налаштовано', { status: 500 })
  }

  const body = await request.json() as GenerateBody
  const { title, season, episode, character, genre, summary, styleContext } = body

  const parts: string[] = ['Напиши нову серію аудіоісторії з такими параметрами:']
  if (title)        parts.push(`Назва: ${title}`)
  if (season)       parts.push(`Сезон: ${season}`)
  if (episode)      parts.push(`Серія: ${episode}`)
  if (character)    parts.push(`Персонаж: ${character}`)
  if (genre)        parts.push(`Жанр: ${genre}`)
  if (summary)      parts.push(`\nКороткий опис / тизер:\n${summary}`)
  if (styleContext) parts.push(`\nСтиль та контекст (уривки попередніх серій або опис стилю):\n${styleContext}`)
  parts.push('\nНапиши повний текст серії. Починай одразу з тексту, без вступних слів.')
  parts.push(`\nПАМʼЯТАЙ: плавний вхід (2–4 речення про настрій Балабонів) → явний гачок → основна частина ПЕРЕВАЖНО З ДІАЛОГІВ 3–5 різних персонажів у форматі «Ім'я: репліка» (Панас:, Ганя:, Микола: …), кожна репліка окремим абзацом з порожнім рядком між абзацами → ПОВНІСТЮ ЗАВЕРШЕНА історія (конфлікт розв'язаний, БЕЗ натяків на продовження) → висновок з 2–3 речень теплої авторської думки (БЕЗ приказки, БЕЗ підписів). Обсяг — близько 1400 слів, СУВОРО від ${MIN_WORDS} до ${MAX_WORDS} (не перевищуй ${MAX_WORDS}). БЕЗ Markdown: жодних зірочок, підкреслень, решіток.`)

  const userMessage = parts.join('\n')

  try {
    const genAI = new GoogleGenerativeAI(apiKey)
    const model = genAI.getGenerativeModel({
      model: 'gemini-2.5-flash',
    }, { apiVersion: 'v1beta' })

    const result = await model.generateContentStream({
      contents: [
        { role: 'user', parts: [{ text: SYSTEM_PROMPT }] },
        { role: 'user', parts: [{ text: userMessage }] },
      ],
    })

    const encoder = new TextEncoder()
    const stream = new ReadableStream<Uint8Array>({
      async start(controller) {
        try {
          for await (const chunk of result.stream) {
            const t = chunk.text()
            if (t) controller.enqueue(encoder.encode(stripInline(t)))
          }
          controller.close()
        } catch (e) {
          controller.error(e)
        }
      },
    })

    return new Response(stream, {
      headers: {
        'Content-Type':  'text/plain; charset=utf-8',
        'Cache-Control': 'no-store',
        'X-Accel-Buffering': 'no',
      },
    })
  } catch (err: unknown) {
    const msg = err instanceof Error ? err.message : 'Помилка API'
    return new Response(msg, { status: 500 })
  }
}
