/** '2026-10-20' → '20 жовтня'. Рік не пишемо: він видно з таблиці дат. */
function humanDate(iso: string): string {
  const [, m, d] = iso.split('-')
  return `${Number(d)} ${MONTHS[Number(m) - 1]}`
}

