/**
 * lib/diia/pension-type.ts
 *
 * Детекція факту інвалідності з поля pensionType (шеринг pension-card через Дію).
 *
 * ⚠️ ПРИВАТНІСТЬ — НЕПОРУШНО:
 *   pensionType містить чутливі медичні дані (група, причина: «загальне
 *   захворювання», «трудове каліцтво», «інвалідність з дитинства» тощо).
 *   Ця функція читає рядок ЛИШЕ в пам'яті й повертає boolean.
 *   pensionType НІКОЛИ не потрапляє в базу, лог, аналітику — нікуди.
 *   У benefit_status пишемо тільки category='disability' (так/ні).
 *
 * Нам потрібен ЛИШЕ факт «є інвалідність», група не важлива.
 *
 * Логіка: у pensionType інвалідність позначена маркером групи «Nгр.»
 * (N = 1/2/3), незалежно від типу пенсії (по інвалідності / за віком /
 * соціальна / у разі втрати годувальника). Наявність «Nгр.» = інвалідність.
 * (Приклади надані Анатолієм / ДП Дія.)
 */

// Цифра 1–3, опційні пробіли, «гр», опційна крапка.
// «підгр.» не спрацьовує — перед «гр» немає цифри впритул.
const GROUP_MARKER = /[123]\s{0,2}гр\.?/iu

/**
 * Повертає true, якщо pensionType вказує на наявність групи інвалідності.
 * Не логує, не зберігає, не повертає жодних деталей — лише boolean.
 */
export function hasDisabilityFromPensionType(
  pensionType: string | null | undefined,
): boolean {
  if (!pensionType) return false
  return GROUP_MARKER.test(pensionType)
}
