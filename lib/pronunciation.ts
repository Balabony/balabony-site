// lib/pronunciation.ts
// ---------------------------------------------------------------------------
// Словник вимови власних назв «Балабонів» для TTS (ElevenLabs multilingual_v2).
//
// Навіщо: модель стабільно перекручує українські власні назви. Демо-озвучення
// йде в грантові пітчі, тож вимова імен прямо впливає на враження.
//
// Підхід (за ТЗ): ТЕКСТОВА ЗАМІНА з наголосами (U+0301 над голосною), НЕ SSML —
// multilingual_v2 SSML повноцінно не тримає. Наголос підбирається на слух і
// таблиця живе й росте — це нормально, додавай рядки за потреби.
//
// Символ наголосу: U+0301 (combining acute accent) ставиться ПІСЛЯ голосної.
// У рядках нижче він уже вшитий у потрібну літеру.
// ---------------------------------------------------------------------------

const A = '\u0301' // combining acute accent (U+0301)

// Таблиця: ключ — слово як воно в тексті (нижній регістр, базова форма),
// значення — те саме слово з наголосом для TTS.
// Наголоси підтверджені Богданом 22.06: МаркО́, отець ПавлО́, решта — як нижче.
export const PRONUNCIATION: Record<string, string> = {
  // — Персонажі —
  'панас': `Пана${A}с`,
  'ганя': `Га${A}ня`,
  'павло': `Павло${A}`,        // отець ПавлО (наголос на О) — підтверджено
  'стрілка': `Стрі${A}лка`,
  'кандиба': `Канди${A}ба`,
  'тодось': `Тодо${A}сь`,
  'охрім': `Охрі${A}м`,
  'сашко': `Сашко${A}`,
  'юхим': `Юхи${A}м`,
  'захар': `Заха${A}р`,
  'марко': `Марко${A}`,        // МаркО (наголос на О) — підтверджено
  'христина': `Христи${A}на`,
  'руслан': `Русла${A}н`,
  'вольодя': `Воло${A}дя`,
  'володя': `Воло${A}дя`,
  'володимир': `Володи${A}мир`,
  'галина': `Гали${A}на`,
  'григорій': `Григо${A}рій`,
  'мотря': `Мо${A}тря`,
  'орися': `Ори${A}ся`,
  'семен': `Семе${A}н`,
  'василь': `Васи${A}ль`,
  'степан': `Степа${A}н`,
  'степанич': `Степа${A}нич`,
  'даринка': `Дари${A}нка`,
  'оверко': `Ове${A}рко`,

  // — Тварини —
  'лиса': `Ли${A}са`,          // корова Гані
  'манька': `Ма${A}нька`,      // коза Орисі
  'пеструха': `Пестру${A}ха`,
  'бровко': `Бровко${A}`,
  'мурчик': `Му${A}рчик`,
  'зірка': `Зі${A}рка`,

  // — Топоніми / назви —
  'балабони': `Балабо${A}ни`,
  'затишне': `Зати${A}шне`,
}

// Літери, які вважаємо «частиною слова» в українському тексті
// (кирилиця + апостроф у середині слова). За межами слова — пунктуація/пробіли.
const WORD_CHARS = "а-яіїєґ'\u02BC"

/**
 * Прогнати текст через словник вимови перед відправкою в TTS.
 * Замінює ЦІЛІ слова (з межами), регістронезалежно, зберігаючи решту тексту.
 *
 * - Матчинг по нижньому регістру ключа; у тексті слово може бути будь-якого регістру.
 * - Замінюється лише точний збіг слова (не підрядок): «Панас» так, «Панасенко» — ні.
 * - Відмінки поки не охоплюються автоматично — клади в словник реальну форму з
 *   тексту (можна кілька записів на різні форми одного імені).
 */
export function applyPronunciation(text: string): string {
  if (!text) return text
  let out = text
  for (const [word, replacement] of Object.entries(PRONUNCIATION)) {
    // межі слова: не-словесний символ (або початок/кінець) ліворуч і праворуч
    const re = new RegExp(
      `(^|[^${WORD_CHARS}])(${escapeRegExp(word)})(?=$|[^${WORD_CHARS}])`,
      'giu'
    )
    out = out.replace(re, (_m, before) => `${before}${replacement}`)
  }
  return out
}

function escapeRegExp(s: string): string {
  return s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
}
