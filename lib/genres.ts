/**
 * Той самий перелік для випадних списків у редакторах.
 * Окремий експорт потрібен через `as const`: GENRES має літеральні типи, і
 * useState(GENRES[0]) виводив би тип «Життєві історії» замість string.
 */
export const GENRE_OPTIONS: readonly string[] = GENRES

/** Чи входить рядок у канонічний перелік. */
export function isGenre(value: string | null | undefined): value is Genre {
  return typeof value === 'string' && (GENRES as readonly string[]).includes(value.trim())
}

