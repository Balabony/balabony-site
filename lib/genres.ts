/**
 * Жанри творів — один список на весь проєкт.
 *
 * Досі їх було два: шістнадцять у редакторі історій і сім у редакторі серій,
 * причому з розбіжностями («Пригоди» проти «Пригода») і зі сміттям на кшталт
 * «Оповідання» (це форма, а не жанр) та «Інше». Через це фільтри на сайті
 * могли не знаходити творів, яким жанр проставили в іншій адмінці.
 *
 * Перелік свідомо короткий: жанр має щось розрізняти для читача, а не бути
 * повною класифікацією літератури. Порядок — від найпоширенішого на
 * платформі до рідкісного, бо в списках вибору це економить час редактора.
 */

export const GENRES = [
  'Життєві історії',
  'Сімейна історія',
  'Романтика',
  'Драма',
  'Гумор',
  'Казка',
  'Про тварин',
  'Військова проза',
  'Різдвяна історія',
  'Детектив',
  'Містика',
  'Історична проза',
  'Фантастика',
  'Пригоди',
] as const

export type Genre = (typeof GENRES)[number]

/** Чи входить рядок у канонічний перелік. */
export function isGenre(value: string | null | undefined): value is Genre {
  return typeof value === 'string' && (GENRES as readonly string[]).includes(value.trim())
}

/**
 * Приведення старих написань до канонічних.
 * Потрібне, бо в базі вже лежать значення з обох попередніх списків.
 */
const ALIASES: Record<string, Genre> = {
  'пригода':          'Пригоди',
  'оповідання':       'Життєві історії',
  'інше':             'Життєві історії',
  'трилер':           'Детектив',
  'бойовик':          'Пригоди',
  'жахи':             'Містика',
  'психологія':       'Драма',
  'біографія':        'Історична проза',
  'сімейні історії':  'Сімейна історія',
  'життєва історія':  'Життєві історії',
  'війна':            'Військова проза',
  'воєнна проза':     'Військова проза',
  'різдвяна':         'Різдвяна історія',
  'тварини':          'Про тварин',
}

export function normalizeGenre(value: string | null | undefined): Genre | null {
  if (!value) return null
  const raw = value.trim()
  if (isGenre(raw)) return raw
  return ALIASES[raw.toLowerCase()] ?? null
}
