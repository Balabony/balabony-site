/** Жанр за адресою сторінки. */
export function genreBySlug(slug: string): Genre | null {
  const found = (Object.keys(GENRE_PAGES) as Genre[]).find(
    (g) => GENRE_PAGES[g].slug === slug.trim().toLowerCase(),
  )
  return found ?? null
}
