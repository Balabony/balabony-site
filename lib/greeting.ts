export function greetName(fullName?: string | null): string | null {
  if (!fullName) return null
  for (const raw of fullName.replace(/[(),.]/g, ' ').split(/\s+/)) {
    const w = raw.trim().toLowerCase().replace(/[’ʼ`]/g, '\'')
    if (w && V[w]) return V[w]
  }
  return null
}
