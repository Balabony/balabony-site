/**
 * Псевдонім, який справді є псевдонімом (20.10.2026).
 *
 * У полі «Псевдонім для публікації» автори часто пишуть «немає», «нема», «ні», «-»,
 * маючи на увазі «псевдоніма немає». Сайт брав це слово за ім'я, і на сторінці автора
 * з'являлося «немає» (випадок Назарія Вівчарика). Тепер такі значення вважаються порожніми —
 * і на сторінках, і під час збереження.
 */
const EMPTY = new Set(['немає', 'нема', 'немa', 'ні', 'нет', 'нету', 'no', 'none', 'n/a', 'na', '-', '—', '–', '.', '0', 'відсутній', 'відсутня', 'без псевдоніма', 'не маю', 'немає псевдоніма'])
export function realPen(v: string | null | undefined): string {
  const t = String(v ?? '').trim()
  return EMPTY.has(t.toLowerCase().replace(/[.!]+$/, '')) ? '' : t
}
