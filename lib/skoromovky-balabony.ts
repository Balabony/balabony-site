export function byTema(slug: string): Skoromovka[] {
  return SKOROMOVKY.filter((s) => s.tags.includes(slug))
}
export function findTema(slug: string): Tema | undefined {
  return TEMY.find((t) => t.slug === slug)
}

/** 1 скоромовка · 2 скоромовки · 5 скоромовок */
export function sk(n: number): string {
  const a = n % 10, b = n % 100
  const w = a === 1 && b !== 11 ? 'скоромовка' : a >= 2 && a <= 4 && (b < 12 || b > 14) ? 'скоромовки' : 'скоромовок'
  return `${n} ${w}`
}
