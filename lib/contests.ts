/**
 * Рядок про призи одним реченням: «Перше місце — 4 000 ₴, друге — 2 500 ₴…».
 * Саме те, що раніше писалося руками в полі `prizes`. Афіші й сторінка
 * конкурсу викликають це, а не зберігають свою копію тексту.
 */
export function prizeLine(c: Contest): string {
  if (c.awards.length === 1) return `${c.awards[0].place} ${c.awards[0].amount}`
  return c.awards.map(a => `${a.place} — ${a.amount}`).join(', ')
}

/**
 * Призовий фонд — сума всіх місць. Зворотний відлік показував для
 * «П'яти вечорів» 8 000 ₴ окремим числом: це 4 000 + 2 500 + 1 500, тобто
 * четверта копія тих самих сум, яка не перерахувалася б сама.
 */
export function prizeFund(c: Contest): string {
  const n = c.awards.reduce((sum, a) => sum + Number(a.amount.replace(/[^0-9]/g, '')), 0)
  return `${n.toLocaleString('uk-UA').replace(/\u00A0/g, ' ')} ₴`
}

/** Найбільша сума конкурсу — для чисел над заголовком. */
export function topPrize(c: Contest): string {
  return c.awards[0]?.amount ?? ''
}

export function findContest(id: string): Contest | undefined {
  return CONTESTS.find(c => c.id === id)
}

/**
 * Чи відкрито прийом. Порівнюємо самі дати, без часу: день закриття
 * вважається робочим до кінця, як і написано в правилах.
 */
export function isOpen(c: Contest, now: Date = new Date()): boolean {
  const today = now.toISOString().slice(0, 10)
  return today >= c.opensAt && today <= c.closesAt
}

/**
 * Чи можна ще досилати серії до ВЖЕ ПОДАНОЇ заявки.
 *
 * ЧОМУ ЦЕ ОКРЕМО ВІД isOpen. У серіальному конкурсі заявка — це синопсис і
 * ПЕРША серія, а решта дев'ять пишуться щотижня до лютого. Якщо закрити
 * форму разом із прийомом заявок 31 жовтня, автор фізично не має куди
 * надіслати другу серію: конкурс зупиниться через тиждень після старту.
 *
 * Тому прийом НОВИХ заявок і дозаливка серій до наявної — різні строки.
 * Дозаливка живе до дати останньої публікації; після неї конкурс уже в
 * підрахунку, і нові тексти в нього не потрапляють.
 */
export function acceptsEpisodes(c: Contest, now: Date = new Date()): boolean {
  const today = now.toISOString().slice(0, 10)
  const until = c.stages.publishUntil ?? c.closesAt
  return today >= c.opensAt && today <= until
}

/** Слова рахуємо однаково у формі, в API і в листі — інакше цифри розійдуться. */
export function countWords(text: string): number {
  const t = text.trim()
  if (!t) return 0
  return t.split(/\s+/).length
}
