const SUBJECTS: Record<AuthorEmailTemplate, string> = {
  intro: 'Ваш кабінет автора на Балабонах — що зробити до запуску',
}

const BUILDERS: Record<AuthorEmailTemplate, (v: Vars) => string> = {
  intro: textIntro,
}

function escapeHtml(s: string) {
  return s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
}

/**
 * Проста ділова верстка: світлий фон, звичайний шрифт.
 * Темні брендові листи гарні для анонсів, але лист, що просить РНОКПП і IBAN,
 * має виглядати як документ з редакції, а не як промо — інакше читається
 * як фішинг.
 */
function toHtml(text: string) {
  const body = text
    .split('\n')
    .map(line => {
      if (!line.trim()) return '<div style="height:12px"></div>'
      const safe = escapeHtml(line).replace(
        /(https?:\/\/[^\s]+)/g,
        '<a href="$1" style="color:#1a5fb4">$1</a>',
      )
      const isHeading = line === line.toUpperCase() && /[А-ЯІЇЄҐ]/.test(line) && line.length < 70
      return isHeading
        ? `<div style="font-weight:700;margin:14px 0 4px">${safe}</div>`
        : `<div>${safe}</div>`
    })
    .join('\n')

  return `<!DOCTYPE html>
<html lang="uk"><body style="margin:0;padding:24px;background:#f4f4f5">
<div style="max-width:620px;margin:0 auto;background:#ffffff;border:1px solid #e4e4e7;border-radius:10px;padding:28px;font-family:Arial,Helvetica,sans-serif;font-size:15px;line-height:1.65;color:#18181b">
${body}
<div style="height:22px"></div>
<div style="border-top:1px solid #e4e4e7;padding-top:14px;font-size:12px;color:#71717a">
Балабони · <a href="${SITE}" style="color:#71717a">balabony.com</a><br>
Ви отримали цей лист як автор, чиї твори публікуються на Балабонах.
</div>
</div>
</body></html>`
}

export function renderAuthorEmail(template: AuthorEmailTemplate, v: Vars) {
  const text = BUILDERS[template](v)
  return { subject: SUBJECTS[template], text, html: toHtml(text) }
}

